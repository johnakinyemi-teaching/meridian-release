#!/usr/bin/env bash
# ======================================================================
#  test_characterization.sh - Characterization & Oracle Test Runner
#  Ticket: MRD-241 / Team: Canopy / Owner: Liene (Task 1: Safety Net)
#
#  Verifies:
#    1. Pure unit tests for nbal_kernel (test_kernel binary)
#    2. Default cropmod run preserves the golden oracle (YIELD = 5.951)
#    3. Optional MERIDIAN_TRACE emits the pinned reference fixture
#    4. Enabling MERIDIAN_TRACE does NOT alter cropmod output (byte-identical)
#    5. Disabling MERIDIAN_TRACE leaves no trace artifact
# ======================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FIXTURES_DIR="${SCRIPT_DIR}/fixtures"
CROPMOD="${SCRIPT_DIR}/cropmod"
TEST_KERNEL="${SCRIPT_DIR}/test_kernel"

echo "================================================================"
echo " Starting Canopy MRD-241 Safety Net / Characterization Tests"
echo " Owner: Liene"
echo "================================================================"

# Ensure binaries exist
if [[ ! -x "${TEST_KERNEL}" || ! -x "${CROPMOD}" ]]; then
    echo "Building required binaries..."
    make -C "${SCRIPT_DIR}" cropmod test_kernel
fi

# ----------------------------------------------------------------------
# Part 1: Run Fortran unit characterization tests
# ----------------------------------------------------------------------
echo ""
echo "[Part 1] Running nbal_kernel Fortran unit tests..."
"${TEST_KERNEL}"

# ----------------------------------------------------------------------
# Part 2: Oracle & Trace Characterization via cropmod execution
# ----------------------------------------------------------------------
TMP_DIR="$(mktemp -d -t canopy_test_XXXXXX)"
trap 'rm -rf "${TMP_DIR}"' EXIT

DECK_SRC="${FIXTURES_DIR}/MERIDIAN.DAT"
REF_OUT="${FIXTURES_DIR}/MERIDIAN_REF.OUT"
REF_TRC="${FIXTURES_DIR}/MERIDIAN_TRACE.REF"

if [[ ! -f "${DECK_SRC}" || ! -f "${REF_OUT}" || ! -f "${REF_TRC}" ]]; then
    echo "ERROR: Missing fixture files in ${FIXTURES_DIR}"
    exit 1
fi

echo ""
echo "[Part 2] Testing default cropmod execution (Oracle Baseline)..."
mkdir -p "${TMP_DIR}/default"
cp "${DECK_SRC}" "${TMP_DIR}/default/MERIDIAN.DAT"
(
    cd "${TMP_DIR}/default"
    unset MERIDIAN_NBAL MERIDIAN_TRACE || true
    "${CROPMOD}" > /dev/null
)

# Verify default output matches reference oracle
if cmp -s "${TMP_DIR}/default/MERIDIAN.OUT" "${REF_OUT}"; then
    echo "  PASS: Default MERIDIAN.OUT matches golden oracle (byte-identical)."
else
    echo "  FAIL: Default MERIDIAN.OUT diverged from golden oracle!"
    diff -u "${REF_OUT}" "${TMP_DIR}/default/MERIDIAN.OUT" | head -n 20
    exit 1
fi

# Verify no trace or nutrient files generated by default
if [[ ! -f "${TMP_DIR}/default/MERIDIAN.TRC" && ! -f "${TMP_DIR}/default/MERIDIAN.NUT" ]]; then
    echo "  PASS: Default run correctly created neither MERIDIAN.TRC nor MERIDIAN.NUT."
else
    echo "  FAIL: Default run generated unexpected diagnostic files!"
    exit 1
fi

echo ""
echo "[Part 3] Testing MERIDIAN_NBAL=1 MERIDIAN_TRACE=1 execution..."
mkdir -p "${TMP_DIR}/trace"
cp "${DECK_SRC}" "${TMP_DIR}/trace/MERIDIAN.DAT"
(
    cd "${TMP_DIR}/trace"
    export MERIDIAN_NBAL=1
    export MERIDIAN_TRACE=1
    "${CROPMOD}" > /dev/null
)

# 1. Output must remain byte-identical even with trace enabled
if cmp -s "${TMP_DIR}/trace/MERIDIAN.OUT" "${REF_OUT}"; then
    echo "  PASS: Traced run MERIDIAN.OUT is byte-identical to oracle."
else
    echo "  FAIL: Traced run MERIDIAN.OUT diverged from oracle!"
    diff -u "${REF_OUT}" "${TMP_DIR}/trace/MERIDIAN.OUT" | head -n 20
    exit 1
fi

# 2. Trace file must exist and match pinned reference
if [[ ! -f "${TMP_DIR}/trace/MERIDIAN.TRC" ]]; then
    echo "  FAIL: MERIDIAN.TRC was not generated under MERIDIAN_TRACE=1!"
    exit 1
fi

if cmp -s "${TMP_DIR}/trace/MERIDIAN.TRC" "${REF_TRC}"; then
    echo "  PASS: MERIDIAN.TRC matches pinned golden trace fixture (byte-identical)."
elif python3 -c '
import sys
a = open(sys.argv[1]).read().splitlines()
b = open(sys.argv[2]).read().splitlines()
assert len(a) == len(b), f"line count {len(a)} != {len(b)}"
for i, (la, lb) in enumerate(zip(a, b), 1):
    if la == lb:
        continue
    ta, tb = la.split(), lb.split()
    assert len(ta) == len(tb), f"line {i} token count mismatch"
    for xa, xb in zip(ta, tb):
        if xa != xb:
            assert abs(float(xa) - float(xb)) <= 1e-5, f"line {i}: {xa} vs {xb}"
' "${REF_TRC}" "${TMP_DIR}/trace/MERIDIAN.TRC"; then
    echo "  PASS: MERIDIAN.TRC matches pinned golden trace fixture within 1e-5 tolerance."
else
    echo "  FAIL: Generated MERIDIAN.TRC differs from reference fixture!"
    diff -u "${REF_TRC}" "${TMP_DIR}/trace/MERIDIAN.TRC" | head -n 20
    exit 1
fi

LINE_COUNT=$(wc -l < "${TMP_DIR}/trace/MERIDIAN.TRC")
if [[ "${LINE_COUNT}" -eq 697 ]]; then
    echo "  PASS: MERIDIAN.TRC contains expected 697 lines (1 header + 174 days x 4 lines)."
else
    echo "  FAIL: MERIDIAN.TRC line count ${LINE_COUNT} != 697"
    exit 1
fi

echo ""
echo "[Part 4] Testing MERIDIAN_NBAL=1 without MERIDIAN_TRACE..."
mkdir -p "${TMP_DIR}/nbal_notrace"
cp "${DECK_SRC}" "${TMP_DIR}/nbal_notrace/MERIDIAN.DAT"
(
    cd "${TMP_DIR}/nbal_notrace"
    export MERIDIAN_NBAL=1
    unset MERIDIAN_TRACE || true
    "${CROPMOD}" > /dev/null
)

if cmp -s "${TMP_DIR}/nbal_notrace/MERIDIAN.OUT" "${REF_OUT}"; then
    echo "  PASS: NBAL-only MERIDIAN.OUT is byte-identical to oracle."
else
    echo "  FAIL: NBAL-only MERIDIAN.OUT diverged from oracle!"
    exit 1
fi

if [[ -f "${TMP_DIR}/nbal_notrace/MERIDIAN.NUT" && ! -f "${TMP_DIR}/nbal_notrace/MERIDIAN.TRC" ]]; then
    echo "  PASS: MERIDIAN.NUT created but MERIDIAN.TRC correctly suppressed."
else
    echo "  FAIL: MERIDIAN_TRACE suppression failed!"
    exit 1
fi

echo ""
echo "================================================================"
echo " ALL CHARACTERIZATION & ORACLE TESTS PASSED (SAFETY NET GREEN)"
echo "================================================================"
exit 0

