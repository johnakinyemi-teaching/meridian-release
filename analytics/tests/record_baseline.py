#!/usr/bin/env python3
"""Record the Archive golden baselines from the code as it is on main.

Run ONCE, before any Archive change, from the repository root:

    python3 analytics/tests/record_baseline.py

Inputs are the real cropmod V2.3 outputs in tests/fixtures/
(cropmod_<STN>_2025.OUT), captured from the default pipeline:

    make all
    python3 tools/gen_packets.py data/spool_2025.bin
    ./ingest/mrd_ingest data/spool_2025.bin data/meridian.db
    # then each station-year's MERIDIAN.OUT copied out of its scratch dir

Outputs (committed beside this script, then never regenerated by the
change that follows; regenerating them after the change would defeat
the point of a characterization test):

    fixtures/baseline_parse_2025.json     what parse.py returns per station
    fixtures/baseline_rows_GUELPH_2025.csv  every parsed GUELPH daily row
    fixtures/baseline_anomaly2_2025.json  what anomaly2 says about each
                                          stored 2025 forecast
"""
from __future__ import annotations

import csv
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from meridian import anomaly2, parse  # noqa: E402
from meridian.store import Store  # noqa: E402

FIX = os.path.join(HERE, "fixtures")
STATIONS = ["BRANTFRD", "CAMBRIDG", "GUELPH", "KITCHNER", "MILTON",
            "WATERLOO"]


def main() -> None:
    parsed = {}
    results = {}
    for stn in STATIONS:
        r = parse.parse_file(os.path.join(FIX, "cropmod_%s_2025.OUT" % stn))
        results[stn] = r
        parsed[stn] = {
            "stnid": r.stnid, "year": r.year, "model": r.model,
            "ndays": r.ndays, "yield_t": r.yield_t,
            "parsed_days": r.parsed_days, "dropped_days": r.dropped_days,
            "days_match": r.days_match,
            "first_row": list(vars(r.rows[0]).values()),
            "last_row": list(vars(r.rows[-1]).values()),
        }
    with open(os.path.join(FIX, "baseline_parse_2025.json"), "w") as fh:
        json.dump(parsed, fh, indent=2, sort_keys=True)
        fh.write("\n")

    with open(os.path.join(FIX, "baseline_rows_GUELPH_2025.csv"), "w",
              newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["doy", "sw", "et", "drain", "biom", "lai"])
        for row in results["GUELPH"].rows:
            w.writerow([row.doy, repr(row.sw), repr(row.et),
                        repr(row.drain), repr(row.biom), repr(row.lai)])

    with tempfile.TemporaryDirectory() as tmp:
        store = Store(os.path.join(tmp, "m.db"))
        for stn in STATIONS:
            store.save_result(results[stn], run_at="2025-10-01T00:00:00")
        reports = anomaly2.analyse_all(store)
        store.close()
    out = {}
    for rep in reports:
        counts = {}
        for a in rep.anomalies:
            key = "%s:%s" % (a.severity.value, a.code)
            counts[key] = counts.get(key, 0) + 1
        out[rep.stnid] = {
            "clean": rep.clean,
            "errors": len(rep.errors()),
            "warnings": len(rep.warnings()),
            "counts": counts,
            "table": rep.as_rows(),
        }
    with open(os.path.join(FIX, "baseline_anomaly2_2025.json"), "w") as fh:
        json.dump(out, fh, indent=2, sort_keys=True)
        fh.write("\n")
    print("baselines written to", FIX)


if __name__ == "__main__":
    main()
