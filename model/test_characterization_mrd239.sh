#!/usr/bin/env bash
# ======================================================================
#  test_characterization_mrd239.sh - Characterization & Oracle Test Runner
#  Ticket: MRD-239 / Team: Canopy / Owner: Liene (Task 1: Safety Net)
#
#  Verifies:
#    1. Pure unit tests for nuptake/nutrient (test_nuptake binary)
#       verifying NAREA=10.0 agreement (GM2_TO_KGHA = NAREA = 10.0, MRD-239)
#    2. Default cropmod run preserves the golden oracle (YIELD = 5.951)
#    3. Default run generates neither MERIDIAN.NUT nor MERIDIAN.TRC
#    4. Latent ticket check: MERIDIAN_NBAL=1 does NOT alter cropmod output (byte-identical)
#    5. Diagnostic file MERIDIAN.NUT is created under MERIDIAN_NBAL=1 with 177 lines
# ======================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FIXTURES_DIR="${SCRIPT_DIR}/fixtures"
CROPMOD="${SCRIPT_DIR}/cropmod"
TEST_NUPTAKE="${SCRIPT_DIR}/test_nuptake"

echo "================================================================"
echo " Starting Canopy MRD-239 Safety Net / Characterization Tests"
echo " Owner: Liene"
echo "================================================================"

# Ensure binaries exist
if [[ ! -x "${TEST_NUPTAKE}" || ! -x "${CROPMOD}" ]]; then
    echo "Building required binaries..."
    make -C "${SCRIPT_DIR}" cropmod test_nuptake
fi

# ----------------------------------------------------------------------
# Part 1: Run Fortran unit characterization tests
# ----------------------------------------------------------------------
echo ""
echo "[Part 1] Running nuptake / nutrient Fortran unit characterization tests..."
"${TEST_NUPTAKE}"

# ----------------------------------------------------------------------
# Part 2: Oracle & Latent Characterization via cropmod execution
# ----------------------------------------------------------------------
TMP_DIR="$(mktemp -d -t canopy_mrd239_XXXXXX)"
trap 'rm -rf "${TMP_DIR}"' EXIT

DECK_SRC="${FIXTURES_DIR}/MERIDIAN.DAT"
REF_OUT="${FIXTURES_DIR}/MERIDIAN_REF.OUT"

if [[ ! -f "${DECK_SRC}" || ! -f "${REF_OUT}" ]]; then
    echo "ERROR: Missing fixture files in ${FIXTURES_DIR}"
    exit 1
fi

echo ""
echo "[Part 2] Testing default cropmod execution (Oracle Baseline)..."
mkdir -p "${TMP_DIR}/default"
cp "${DECK_SRC}" "${TMP_DIR}/default/MERIDIAN.DAT"
(
    cd "${TMP_DIR}/default"
    unset MERIDIAN_NBAL MERIDIAN_TRACE || true
    "${CROPMOD}" > /dev/null
)

# Verify default output matches reference oracle
if cmp -s "${TMP_DIR}/default/MERIDIAN.OUT" "${REF_OUT}"; then
    echo "  PASS: Default MERIDIAN.OUT matches golden oracle (byte-identical)."
else
    echo "  FAIL: Default MERIDIAN.OUT diverged from golden oracle!"
    diff -u "${REF_OUT}" "${TMP_DIR}/default/MERIDIAN.OUT" | head -n 20
    exit 1
fi

# Verify no trace or nutrient files generated by default
if [[ ! -f "${TMP_DIR}/default/MERIDIAN.TRC" && ! -f "${TMP_DIR}/default/MERIDIAN.NUT" ]]; then
    echo "  PASS: Default run correctly created neither MERIDIAN.TRC nor MERIDIAN.NUT."
else
    echo "  FAIL: Default run generated unexpected diagnostic files!"
    exit 1
fi

echo ""
echo "[Part 3] Testing latent behaviour under MERIDIAN_NBAL=1..."
mkdir -p "${TMP_DIR}/nbal"
cp "${DECK_SRC}" "${TMP_DIR}/nbal/MERIDIAN.DAT"
(
    cd "${TMP_DIR}/nbal"
    export MERIDIAN_NBAL=1
    unset MERIDIAN_TRACE || true
    "${CROPMOD}" > /dev/null
)

# 1. Output must remain byte-identical even with NBAL enabled (latent ticket rule)
if cmp -s "${TMP_DIR}/nbal/MERIDIAN.OUT" "${REF_OUT}"; then
    echo "  PASS: MERIDIAN_NBAL=1 MERIDIAN.OUT is byte-identical to golden oracle."
else
    echo "  FAIL: MERIDIAN_NBAL=1 MERIDIAN.OUT diverged from oracle!"
    diff -u "${REF_OUT}" "${TMP_DIR}/nbal/MERIDIAN.OUT" | head -n 20
    exit 1
fi

# 2. Nutrient diagnostic file must exist
if [[ ! -f "${TMP_DIR}/nbal/MERIDIAN.NUT" ]]; then
    echo "  FAIL: MERIDIAN.NUT was not generated under MERIDIAN_NBAL=1!"
    exit 1
fi

LINE_COUNT=$(wc -l < "${TMP_DIR}/nbal/MERIDIAN.NUT")
if [[ "${LINE_COUNT}" -eq 177 ]]; then
    echo "  PASS: MERIDIAN.NUT contains expected 177 lines (2 headers + 174 days + 1 END marker)."
else
    echo "  FAIL: MERIDIAN.NUT line count ${LINE_COUNT} != 177"
    exit 1
fi

# 3. Check header line of MERIDIAN.NUT
HEADER_LINE=$(head -n 1 "${TMP_DIR}/nbal/MERIDIAN.NUT")
if [[ "${HEADER_LINE}" == *"MERIDIAN NBAL V0.1"* ]]; then
    echo "  PASS: MERIDIAN.NUT header matches 'MERIDIAN NBAL V0.1'."
else
    echo "  FAIL: Unexpected MERIDIAN.NUT header: ${HEADER_LINE}"
    exit 1
fi

echo ""
echo "================================================================"
echo " ALL MRD-239 CHARACTERIZATION & ORACLE TESTS PASSED (SAFETY NET GREEN)"
echo "================================================================"
exit 0
